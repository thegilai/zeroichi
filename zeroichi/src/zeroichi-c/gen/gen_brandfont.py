"""Make src/fontbrand.c: Zero Ichi's own letters (v52) for its menus - Poppins
(Medium and Bold; SIL Open Font License, see fonts/OFL.txt in the zeroichi
folder), pre-rendered by Pillow like gen_fonts.py's (fill only, no outline).
usage: python3 gen_brandfont.py OUT.c"""
import sys
from PIL import Image, ImageDraw, ImageFont

D = "/usr/share/fonts/truetype/google-fonts/"
OUT = sys.argv[1]
TEXT = [chr(c) for c in range(32, 127)] + list("°‹›·…×•")
SIZES = [("Poppins-Medium.ttf", 11, 0), ("Poppins-Medium.ttf", 12, 0), ("Poppins-Medium.ttf", 14, 0),
         ("Poppins-Medium.ttf", 15, 0), ("Poppins-Bold.ttf", 16, 1), ("Poppins-Bold.ttf", 22, 1)]

data = bytearray()
fonts = []
for name, size, bold in SIZES:
    f = ImageFont.truetype(D + name, size)
    asc, desc = f.getmetrics()
    glyphs = []
    for ch in TEXT:
        adv = f.getlength(ch)
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        raw = b""
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            raw = im.tobytes()
        glyphs.append((ord(ch), int(round(adv * 64)), (x0, y0, w, h, len(data))))
        data.extend(raw)
    fonts.append((size, bold, asc, desc, glyphs))

out = ["/* Generated by gen/gen_brandfont.py (Poppins Medium / Bold, pre-rendered by",
       " * Pillow; Poppins: SIL Open Font License) - do not edit. */", '#include "font.h"', ""]
hexrows = [", ".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
out.append(f"static const unsigned char BRAND_BITS[{len(data)}] = {{\n    " + ",\n    ".join(hexrows) + "\n};")
for size, bold, asc, desc, glyphs in fonts:
    rows = [f"    {{{cp}, {adv}, {{{fx}, {fy}, {fw}, {fh}, {fo}}}, {{0, 0, 0, 0, 0}}}}"
            for cp, adv, (fx, fy, fw, fh, fo) in glyphs]
    out.append(f"static const Glyph bglyphs_{size}_{bold}[] = {{\n" + ",\n".join(rows) + "\n};")
out.append("const Font BRAND_FONTS[] = {")
for size, bold, asc, desc, glyphs in fonts:
    out.append(f"    {{{size}, 0, {asc}, {desc}, {len(glyphs)}, bglyphs_{size}_{bold}, BRAND_BITS, {bold}}},")
out.append("};")
out.append(f"const int NBRAND_FONTS = {len(fonts)};")
open(OUT, "w").write("\n".join(out) + "\n")
print("brand fonts:", [(s, b, len(g)) for s, b, _, _, g in fonts], "bytes", len(data))
