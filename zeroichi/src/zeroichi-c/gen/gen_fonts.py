"""Make src/fontdata.c: the letters Zero Ichi draws, pre-rendered by Pillow from
DejaVu Sans Bold (the font the Python version used) - each as a grey mask,
plus a second mask with the black outline (Pillow's stroke)."""
import sys
from PIL import Image, ImageDraw, ImageFont
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
OUT = sys.argv[1]
TEXT = [chr(c) for c in range(32, 127)] + list("°▲▼●▶★•…×")
SIZES = [(12, 2, TEXT), (14, 2, TEXT), (16, 2, TEXT), (18, 2, TEXT), (22, 2, TEXT), (30, 2, TEXT),
         (120, 5, list("0123456789"))]

data = bytearray()
fonts = []
for size, stroke, chars in SIZES:
    f = ImageFont.truetype(FONT, size)
    asc, desc = f.getmetrics()
    glyphs = []
    for ch in chars:
        adv = f.getlength(ch)
        masks = []
        for s in (0, stroke):
            box = f.getbbox(ch, anchor="ls", stroke_width=s)
            x0, y0, x1, y1 = box
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            if w and h:
                im = Image.new("L", (w, h), 0)
                ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls",
                                        stroke_width=s, stroke_fill=255)
                raw = im.tobytes()
            else:
                raw = b""
            masks.append((x0, y0, w, h, len(data)))
            data.extend(raw)
        glyphs.append((ord(ch), int(round(adv * 64)), masks))
    fonts.append((size, stroke, asc, desc, glyphs))

out = ['/* Generated by gen/gen_fonts.py (DejaVu Sans Bold, pre-rendered by Pillow;',
       ' * DejaVu fonts: Bitstream Vera licence) - do not edit. */', '#include "font.h"', '']
for size, stroke, asc, desc, glyphs in fonts:
    rows = []
    for cp, adv, ((fx, fy, fw, fh, fo), (sx, sy, sw, sh, so)) in glyphs:
        rows.append(f"    {{{cp}, {adv}, {{{fx}, {fy}, {fw}, {fh}, {fo}}}, {{{sx}, {sy}, {sw}, {sh}, {so}}}}}")
    out.append(f"static const Glyph glyphs_{size}[] = {{\n" + ",\n".join(rows) + "\n};")
out.append("const Font FONTS[] = {")
for size, stroke, asc, desc, glyphs in fonts:
    out.append(f"    {{{size}, {stroke}, {asc}, {desc}, {len(glyphs)}, glyphs_{size}, NULL, 0}},")
out.append("};")
out.append(f"const int NFONTS = {len(fonts)};")
hexrows = [", ".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40)]
out.append(f"const unsigned char FONT_BITS[{len(data)}] = {{\n    " + ",\n    ".join(hexrows) + "\n};")
open(OUT, "w").write("\n".join(out) + "\n")
print("fonts:", [(s, len(g)) for s, _, _, _, g in fonts], "bytes", len(data))
